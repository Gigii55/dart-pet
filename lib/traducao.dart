  static String _traduzLista(String? texto, Map<String, String> dic) {
    if (texto == null || texto.trim().isEmpty) return '';
    return texto
        .split(',')
        .map((p) => p.trim())
        .where((p) => p.isNotEmpty)
        .map((p) => dic[p.toLowerCase()] ?? p)
        .join(', ');
  }

  static String? temperamento(String? t) {
    final r = _traduzLista(t, _temperamento);
    return r.isEmpty ? null : r;
  }

  static String? grupo(String? g) {
    final r = _traduzLista(g, _grupo);
    return r.isEmpty ? null : r;
  }

  static String? origem(String? o) {
    final r = _traduzLista(o, _origem);
    return r.isEmpty ? null : r;
  }

  static String? vida(String? v) {
    if (v == null || v.trim().isEmpty) return null;
    final texto = v
        .replaceAll('years', 'anos')
        .replaceAll('year', 'ano')
        .trim();
    return texto.contains('ano') ? texto : '$texto anos';
  }

  static String? medida(String? m) {
    if (m == null || m.trim().isEmpty) return null;
    return m.replaceAll('Female', 'Fêmea').replaceAll('Male', 'Macho');
  }

  static String nomeRaca(String nome) => _racas[nome.toLowerCase()] ?? nome;

  static String termoBusca(String termo) =>
      _buscaPtEn[termo.trim().toLowerCase()] ?? termo.trim();

  static String? comUnidade(String? texto, String unidade) {
    if (texto == null || texto.trim().isEmpty) return null;
    return texto.replaceAllMapped(
      RegExp(r'\d+(?:[.,]\d+)?(?:\s*-\s*\d+(?:[.,]\d+)?)?'),
      (m) => '${m[0]} $unidade',
    );
  }
